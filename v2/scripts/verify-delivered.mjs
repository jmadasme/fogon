import { firefox } from "playwright";
const browser = await firefox.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1400, height: 900 }, locale: "es-CL" });
const page = await context.newPage();
await page.goto("http://localhost:3000/login", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Cliente/i }).first().click();
await page.getByRole("button", { name: "Ingresar", exact: true }).click();
await page.waitForURL("http://localhost:3000/");
await page.goto("http://localhost:3000/orders", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1500);
const link = page.locator('a[href^="/order/"]').filter({ hasText: "FOG-XZQ25E" }).first();
await link.click();
await page.waitForURL(/\/order\//);
await page.locator("h1").filter({ hasText: "¡Buen provecho!" }).waitFor({ timeout: 15000 });
await page.waitForTimeout(1000);
await page.screenshot({ path: "/home/jma/Documents/Proyect/fogon/assets/screenshots/qa-e2e/92460/18b-cliente-entregado.png", fullPage: false });
const body = await page.locator("body").innerText();
console.log("h1 ok:", body.includes("¡Buen provecho!"));
console.log("entregado badge:", body.includes("Entregado"));
console.log("pagado:", body.includes("Pagado"));
console.log("raw labels left:", ["PAYMENT_CASH_PENDING", "PENDING_COURIER"].filter((x) => body.includes(x)));
console.log("reviewed:", body.includes("Ya calificaste"));
await browser.close();
