import { firefox } from "playwright";
const browser = await firefox.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1400, height: 900 }, locale: "es-CL" });
const page = await context.newPage();
await page.goto("http://localhost:3000/login", { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Cliente/i }).first().click();
await page.getByRole("button", { name: "Ingresar", exact: true }).click();
await page.waitForURL("http://localhost:3000/");
await page.goto("http://localhost:3000/orders", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(1500);
const link = page.locator('a[href^="/order/"]').filter({ hasText: "FOG-JFNHKZ" }).first();
await link.click();
await page.waitForURL(/\/order\//);
await page.locator("h1").filter({ hasText: "Pedido no completado" }).waitFor({ timeout: 15000 });
await page.waitForTimeout(800);
await page.screenshot({ path: "/home/jma/Documents/Proyect/fogon/assets/screenshots/qa-e2e/92460/25b-cliente-cancelado.png", fullPage: false });
const body = await page.locator("body").innerText();
console.log("h1 cancelado:", body.includes("Pedido no completado"));
console.log("badge pago cancelado:", body.includes("Cancelado"));
console.log("sin cobro:", body.includes("No se realizó ningún cobro"));
console.log("sin ETA:", !body.includes("Llega aproximadamente"));
await browser.close();
