import { chromium } from "playwright";
const BASE = "http://localhost:3000";
const CODE = process.env.CODE ?? "FOG-GRGWMH";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: "es-CL" });
const page = await context.newPage();
await page.goto(`${BASE}/login`, { waitUntil: "networkidle" });
await page.getByRole("button", { name: /Admin/i }).first().click();
await page.getByRole("button", { name: "Ingresar", exact: true }).click();
await page.waitForURL(/\/admin/, { timeout: 20000 });
await page.goto(`${BASE}/admin/orders`, { waitUntil: "domcontentloaded" });
await page.locator('input[name="q"]').fill(CODE);
await page.getByRole("button", { name: "Filtrar" }).click();
await page.waitForTimeout(1500);
const row = page.locator("tr").filter({ hasText: CODE }).first();
await row.waitFor({ timeout: 15000 });
await row.getByRole("button", { name: "Reembolsar" }).click();
await page.waitForTimeout(2000);
const updated = await page.locator("tr").filter({ hasText: CODE }).first().innerText();
console.log(updated.replace(/\n/g, " | "));
console.log("refunded", updated.includes("Reembolsado"));
await page.screenshot({ path: "/home/jma/Documents/Proyect/fogon/assets/screenshots/qa-native/round2/07-admin-reembolso.png" });
await browser.close();
